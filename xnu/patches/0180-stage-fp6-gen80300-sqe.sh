#!/bin/bash
# Stage the pinned FP6 Gen8.3 SQE instructions as generated C data; do not commit firmware.
set -euo pipefail

case "${MACHINE_CONFIG:-}" in FP6) ;; *) exit 0 ;; esac
[[ -d bsd/dev ]] || exit 1

fw_commit=e58a5be8fa0fb6bc5a5f2e29cc01c036ccf75710
fw_sha256=38fd00147e8b752dd29c53a0badac8f94b1dbd89dc06f5b1c372d3428cd1b906
fw_tmp=$(mktemp)
trap 'rm -f "$fw_tmp"' EXIT
if [[ -n "${FP6_SQE_SOURCE:-}" ]]; then
    cp "$FP6_SQE_SOURCE" "$fw_tmp"
else
    curl -fsSL --retry 3 -o "$fw_tmp" \
        "https://raw.githubusercontent.com/FairBlobs/FP6-firmware/$fw_commit/gen80300_sqe.fw"
fi
got=$(shasum -a 256 "$fw_tmp" 2>/dev/null | cut -d' ' -f1 || sha256sum "$fw_tmp" | cut -d' ' -f1)
[[ "$got" == "$fw_sha256" ]] || { echo "gen80300_sqe.fw hash mismatch: $got" >&2; exit 1; }

python3 - "$fw_tmp" bsd/dev/fp6_sqe_fw.h <<'PY'
import hashlib, struct, sys

blob = open(sys.argv[1], 'rb').read()
expected = '38fd00147e8b752dd29c53a0badac8f94b1dbd89dc06f5b1c372d3428cd1b906'
assert len(blob) == 84564 and hashlib.sha256(blob).hexdigest() == expected
assert len(blob) > 4 and (len(blob) - 4) % 4 == 0
version = struct.unpack_from('<I', blob, 4)[0]
payload = blob[4:]
assert version == 0x01100067 and len(payload) == 84560

with open(sys.argv[2], 'w') as out:
    out.write('/* Generated by 0180-stage-fp6-gen80300-sqe.sh; not in git. */\n')
    out.write('#define FP6_SQE_FW_VERSION 0x%08xu\n' % version)
    out.write('#define FP6_SQE_FW_SIZE %du\n' % len(payload))
    out.write('#define FP6_SQE_FW_SHA256 "%s"\n' % expected)
    out.write('static const unsigned char fp6_sqe_fw[FP6_SQE_FW_SIZE] = {\n')
    for i in range(0, len(payload), 12):
        out.write('\t' + ', '.join('0x%02x' % b for b in payload[i:i + 12]) + ',\n')
    out.write('};\n')
PY
echo "staged Gen8.3 SQE v0x01100067 payload=84560 sha256=$fw_sha256 in bsd/dev/fp6_sqe_fw.h"
