#!/bin/bash
# dxb runs patches/*.sh from the XNU source root before applying *.patch.
# Stages the A6xx GMU firmware as a generated header; no firmware lives in git.
set -euo pipefail

[[ "${MACHINE_CONFIG:-}" == SWEET ]] || exit 0
[[ -d bsd/dev ]] || exit 1

# linux-firmware qcom/a630_gmu.bin, the image mainline Linux loads on A618.
# Pinned to an immutable commit and verified by hash.
fw_commit=a2dcb924f0897368b0b4f305cbf9808cdda90ce0
fw_sha256=da8d9b1b1f5c1a0b311f32567093b4828f3c80031dd8435f91ac13c664e173a6
fw_tmp=$(mktemp)
trap 'rm -f "$fw_tmp"' EXIT
curl -fsSL --retry 3 -o "$fw_tmp" \
    "https://git.kernel.org/pub/scm/linux/kernel/git/firmware/linux-firmware.git/plain/qcom/a630_gmu.bin?id=$fw_commit"
got=$(shasum -a 256 "$fw_tmp" 2>/dev/null | cut -d' ' -f1 || sha256sum "$fw_tmp" | cut -d' ' -f1)
[[ "$got" == "$fw_sha256" ]] || { echo "a630_gmu.bin hash mismatch: $got" >&2; exit 1; }

python3 - "$fw_tmp" bsd/dev/sweet_gpu_fw.h <<'PY'
import sys
data = open(sys.argv[1], 'rb').read()
assert len(data) == 0x8000, len(data)
with open(sys.argv[2], 'w') as out:
    out.write('/* Generated by 0086-stage-gpu-firmware.sh; not in git. */\n')
    out.write('static const unsigned char sweet_gpu_gmu_fw[] = {\n')
    for i in range(0, len(data), 12):
        out.write('\t' + ', '.join('0x%02x' % b for b in data[i:i + 12]) + ',\n')
    out.write('};\n')
PY
echo "staged bsd/dev/sweet_gpu_fw.h"
