#!/bin/bash
# Stage the FP6 Gen8.3 signed ZAP image as generated C data; never commit blobs.
set -euo pipefail

case "${MACHINE_CONFIG:-}" in FP6) ;; *) exit 0 ;; esac
[[ -d bsd/dev ]] || exit 1

fw_commit=e58a5be8fa0fb6bc5a5f2e29cc01c036ccf75710
fw_sha256=a91c411027746d4c3389a69b66f25d21eb646e89f2de5eed3f698e370f83f26c
fw_tmp=$(mktemp)
trap 'rm -f "$fw_tmp"' EXIT
if [[ -n "${FP6_ZAP_SOURCE:-}" ]]; then
    cp "$FP6_ZAP_SOURCE" "$fw_tmp"
else
    curl -fsSL --retry 3 -o "$fw_tmp" \
        "https://raw.githubusercontent.com/FairBlobs/FP6-firmware/$fw_commit/gen80300_zap.mbn"
fi
got=$(shasum -a 256 "$fw_tmp" 2>/dev/null | cut -d' ' -f1 || sha256sum "$fw_tmp" | cut -d' ' -f1)
[[ "$got" == "$fw_sha256" ]] || { echo "gen80300_zap.mbn hash mismatch: $got" >&2; exit 1; }

python3 - "$fw_tmp" bsd/dev/fp6_zap_fw.h <<'PY'
import hashlib, struct, sys

blob = open(sys.argv[1], 'rb').read()
assert len(blob) == 12088 and hashlib.sha256(blob).hexdigest() == \
    'a91c411027746d4c3389a69b66f25d21eb646e89f2de5eed3f698e370f83f26c'
assert blob[:7] == b'\x7fELF\x01\x01\x01'
eh = struct.unpack_from('<16sHHIIIIIHHHHHH', blob, 0)
assert eh[1] == 2 and eh[2] == 164 and eh[4] == 0x1000
assert eh[5] == 52 and eh[8] == 52 and eh[9] == 32 and eh[10] == 3
ph = [struct.unpack_from('<IIIIIIII', blob, eh[5] + i * eh[9]) for i in range(eh[10])]
assert ph[0][0] == 0 and ph[0][4] == 0x94
load = [p for p in ph if p[0] == 1]
hashes = [p for p in ph if p[0] != 1 and (p[6] & 0x0f000000) == 0x02000000]
assert len(load) == len(hashes) == 1
p = load[0]
assert (p[1], p[2], p[3], p[4], p[5], p[6] & 0x08000000) == (0x1000, 0x1000, 0x1000, 0x378, 0x378, 0x08000000)
h = hashes[0]
assert (h[1], h[4]) == (0x2000, 0xF38)
metadata = blob[:ph[0][4]] + blob[h[1]:h[1] + h[4]]
segment = blob[p[1]:p[1] + p[4]]
assert len(metadata) == 0xFCC and len(segment) == 0x378

with open(sys.argv[2], 'w') as out:
    out.write('/* Generated by 0126-stage-fp6-gen80300-zap.sh; not in git. */\n')
    for name, data in [('fp6_zap_metadata', metadata), ('fp6_zap_segment', segment)]:
        out.write('static const unsigned char %s[%d] = {\n' % (name, len(data)))
        for i in range(0, len(data), 12):
            out.write('\t' + ', '.join('0x%02x' % b for b in data[i:i + 12]) + ',\n')
        out.write('};\n')
PY
echo "staged bsd/dev/fp6_zap_fw.h"
