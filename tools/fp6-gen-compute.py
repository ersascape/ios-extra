#!/usr/bin/env python3
"""Turn a Mesa freedreno `.rd` capture of one computerator dispatch into the C
data header used by the FP6 compute probe.

Capture it on a host with the pinned Mesa build (see docs/FP6_METAL_PORT_MAP.md):

  LD_PRELOAD=libfreedreno_noop_drm_shim.so FD_GPU_ID=810 \\
  FD_RD_DUMP=enable,full FD_RD_DUMP_PATH=DIR \\
  computerator -f examples/buf-init.asm -g 1,1,1

The stream holds Mesa's fake IOVAs. This tool records where the shader and the
UAV descriptor addresses sit so the kernel can patch real GPU addresses in, and
keeps the shader words, the 16-dword buffer descriptor and the initial data.
"""
import gzip
import struct
import sys

RD_GPUADDR, RD_BUFFER_CONTENTS, RD_CMDSTREAM_ADDR, RD_CHIP_ID = 3, 12, 6, 14


def parse(path):
    data = gzip.open(path).read()
    off, bos, cur, cmd, chip = 0, [], None, None, None
    while off < len(data):
        kind, size = struct.unpack_from('<II', data, off)
        off += 8
        payload = data[off:off + size]
        off += size
        if kind == RD_GPUADDR:
            cur = struct.unpack_from('<II', payload)
        elif kind == RD_BUFFER_CONTENTS:
            bos.append((cur[0], cur[1], payload))
        elif kind == RD_CMDSTREAM_ADDR:
            cmd = struct.unpack_from('<II', payload)
        elif kind == RD_CHIP_ID:
            chip = struct.unpack_from('<I', payload)[0]
    return bos, cmd, chip


def words(blob):
    return list(struct.unpack('<%dI' % (len(blob) // 4), blob))


def find_bo(bos, addr):
    for base, size, blob in bos:
        if base <= addr < base + size:
            return base, blob
    raise SystemExit('no BO holds 0x%x' % addr)


def relocs(stream, addr):
    """(lo_index, hi_index) pairs for every dword equal to addr.

    CP_LOAD_STATE6 stores lo, hi back to back; CP_CONTEXT_REG_BUNCH stores
    reg, lo, reg+1, hi, so hi sits two dwords after lo.
    """
    out = []
    for i, w in enumerate(stream):
        if w != addr:
            continue
        if stream[i + 1] == 0:
            out.append((i, i + 1))
        elif stream[i + 2] == 0 and stream[i + 1] < 0x10000:
            out.append((i, i + 2))
        else:
            raise SystemExit('cannot place high dword for reloc at %d' % i)
    return out


def emit_array(name, values, per_line=8, kind='uint32_t'):
    lines = ['static const %s %s[%d] = {' % (kind, name, len(values))]
    for i in range(0, len(values), per_line):
        chunk = ', '.join('0x%08xu' % v for v in values[i:i + per_line])
        lines.append('\t' + chunk + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    if len(sys.argv) != 3:
        raise SystemExit('usage: fp6-gen-compute.py CAPTURE.rd OUT.h')
    bos, cmd, chip = parse(sys.argv[1])
    if chip != 0x44010000:
        raise SystemExit('capture is not an A810 chip id: 0x%x' % (chip or 0))
    cmd_addr, cmd_dwords = cmd
    base, blob = find_bo(bos, cmd_addr)
    start = cmd_addr - base
    stream = words(blob[start:start + cmd_dwords * 4])

    # Shader BO and UAV descriptor BO: the BOs the stream names via LOAD_STATE6.
    named = {}
    for b_base, b_size, _ in bos:
        n = relocs(stream, b_base)
        if n:
            named[b_base] = n
    if len(named) != 3:
        raise SystemExit('expected shader, UAV descriptor and control BOs, found %s' % sorted(named))
    contents = {a: p for a, _, p in bos}
    # The descriptor has TYPE=TEX_BUFFER (bits 17..19 == 4) and a nonzero count.
    uav_addr = next(a for a in named
                    if (words(contents[a])[1] >> 17) & 7 == 4 and words(contents[a])[2])
    # The control BO is zero-filled (CP_EVENT_WRITE7 targets it); the shader is not.
    others = [a for a in named if a != uav_addr]
    shader_addr = next(a for a in others if any(contents[a]))
    control_addr = next(a for a in others if a != shader_addr)
    shader_blob = next(p for a, _, p in bos if a == shader_addr)
    uav_blob = next(p for a, _, p in bos if a == uav_addr)
    sw = words(shader_blob)
    last = max(i for i, w in enumerate(sw) if w)
    shader = sw[:((last // 16) + 1) * 16]
    desc = words(uav_blob)[:16]
    buf_iova = desc[0] | ((desc[1] & 0x1ffff) << 32)
    buf_base, buf_blob = find_bo(bos, buf_iova)
    elements = desc[2] & 0x7fff
    buf = words(buf_blob[buf_iova - buf_base:buf_iova - buf_base + elements * 4])

    out = ['/* Generated by tools/fp6-gen-compute.py from a Mesa freedreno A810 capture of',
           ' * computerator examples/buf-init.asm (8 invocations, each adds 5 to a word).',
           ' * Do not edit; regenerate. Addresses in the stream are Mesa shim IOVAs that',
           ' * the probe replaces through the relocation tables. */',
           '#ifndef FP6_GPU_COMPUTE_TEST_H',
           '#define FP6_GPU_COMPUTE_TEST_H',
           '#define FP6_CS_SHIM_SHADER 0x%08xu' % shader_addr,
           '#define FP6_CS_SHIM_UAV    0x%08xu' % uav_addr,
           '#define FP6_CS_SHIM_CONTROL 0x%08xu' % control_addr,
           '#define FP6_CS_ELEMENTS    %uu' % elements,
           emit_array('fp6_cs_stream', stream),
           emit_array('fp6_cs_shader', shader),
           emit_array('fp6_cs_uav_template', desc),
           emit_array('fp6_cs_data_init', buf)]
    for label, addr in (('shader', shader_addr), ('uav', uav_addr), ('control', control_addr)):
        pairs = named[addr]
        flat = [v for pair in pairs for v in pair]
        out.append('#define FP6_CS_%s_RELOCS %uu' % (label.upper(), len(pairs)))
        out.append(emit_array('fp6_cs_%s_reloc' % label, flat, 8, 'uint16_t')
                   .replace('0x%08xu' % 0, '0'))
    out.append('#endif')
    text = '\n'.join(out) + '\n'
    # uint16_t tables do not need 8-digit literals.
    import re
    text = re.sub(r'(fp6_cs_(?:shader|uav|control)_reloc\[\d+\] = \{[^}]*\})',
                  lambda m: re.sub(r'0x0000([0-9a-f]{4})u', r'0x\1', m.group(1)), text)
    open(sys.argv[2], 'w').write(text)
    print('stream=%d dwords shader=%d dwords relocs shader=%d uav=%d control=%d elements=%d'
          % (len(stream), len(shader), len(named[shader_addr]), len(named[uav_addr]),
             len(named[control_addr]), elements))


if __name__ == '__main__':
    main()
